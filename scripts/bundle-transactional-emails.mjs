#!/usr/bin/env node
/**
 * Bundles the React Email templates in emails/ into a single self-contained ESM file that the
 * Supabase Edge (Deno) runtime can import. Re-run after editing anything under emails/:
 *
 *   pnpm email:build
 *
 * Use `--check` in CI to fail when the committed bundle is stale.
 */
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "supabase/functions/_shared");
const bundlePath = path.join(outDir, "transactional-email.bundle.mjs");
const typesPath = path.join(outDir, "transactional-email.bundle.d.ts");
const checkOnly = process.argv.includes("--check");

const header = [
  "// GENERATED by scripts/bundle-transactional-emails.mjs from emails/src — do not edit.",
  "// Regenerate with `pnpm email:build`.",
].join("\n");

// @react-email/render lazy-imports prettier only for `pretty()`, which the Edge never calls.
const stubPrettier = {
  name: "stub-prettier",
  setup(pluginBuild) {
    pluginBuild.onResolve({ filter: /^prettier(\/|$)/ }, (args) => ({ path: args.path, namespace: "stub-prettier" }));
    pluginBuild.onLoad({ filter: /.*/, namespace: "stub-prettier" }, () => ({
      contents: 'throw new Error("prettier is not bundled for the Edge runtime");',
      loader: "js",
    }));
  },
};

const result = await build({
  plugins: [stubPrettier],
  absWorkingDir: root,
  entryPoints: ["emails/src/edge-entry.ts"],
  bundle: true,
  write: false,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  conditions: ["deno", "worker", "browser", "import", "default"],
  mainFields: ["module", "main"],
  jsx: "automatic",
  tsconfig: "emails/tsconfig.json",
  define: { "process.env.NODE_ENV": '"production"' },
  minify: true,
  legalComments: "none",
  banner: { js: `${header}\n/* @ts-self-types="./transactional-email.bundle.d.ts" */` },
  metafile: true,
});

const bundle = result.outputFiles[0].text;

const sourceTypes = await readFile(path.join(root, "emails/src/types.ts"), "utf8");
const declarations = [
  header,
  "",
  sourceTypes.trim(),
  "",
  "export declare function renderInviteEmail(input: InviteEmailInput): Promise<RenderedEmail>;",
  "export declare function renderDebtReminderEmail(input: DebtReminderEmailInput): Promise<RenderedEmail>;",
  "",
].join("\n");

if (checkOnly) {
  const [currentBundle, currentTypes] = await Promise.all([
    readFile(bundlePath, "utf8").catch(() => ""),
    readFile(typesPath, "utf8").catch(() => ""),
  ]);
  if (currentBundle !== bundle || currentTypes !== declarations) {
    console.error("transactional-email bundle is stale — run `pnpm email:build` and commit the result.");
    process.exit(1);
  }
  console.log("transactional-email bundle is up to date.");
} else {
  await writeFile(bundlePath, bundle);
  await writeFile(typesPath, declarations);
  const kb = (Buffer.byteLength(bundle) / 1024).toFixed(1);
  console.log(`Wrote ${path.relative(root, bundlePath)} (${kb} KB) and ${path.relative(root, typesPath)}`);
}
