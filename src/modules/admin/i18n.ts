export function getAdminLocale(language?: string) {
  return language?.startsWith("vi") ? "vi-VN" : "en-US";
}

export function useAdminTranslation() {
  const { t, i18n } = useTranslation();
  const language = i18n.resolvedLanguage || i18n.language;
  const tAdmin = useCallback(
    (key: string, options?: TOptions): string => String(t(`admin.${key}`, options)),
    [t],
  );

  return {
    tAdmin,
    t,
    i18n,
    locale: getAdminLocale(language),
  };
}
